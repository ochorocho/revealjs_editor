/**
 * Frontend importmap registration for this extension.
 *
 * Single prefix mapping: anything under `@ochorocho/revealjs-editor/...`
 * resolves to `Resources/Public/JavaScript/...`. TYPO3's AssetCollector
 * publishes the path through `/_assets/<hash>/JavaScript/...`. Today this
 * surfaces:
 *
 *   - `@ochorocho/revealjs-editor/ShikiHighlight.js` — always-loaded
 *     client-side highlighter (loaded by RevealJsShikiAssetsProcessor on
 *     every doktype-1731 page; replaces `<pre><code class="language-X">`
 *     blocks with Shiki output on DOMContentLoaded).
 *   - `@ochorocho/revealjs-editor/RevealEditableShiki.js` — `<reveal-editable-shiki>`
 *     textarea-overlay custom element (loaded only in visual_editor's
 *     edit-mode preview iframe; same processor, gated on ?editMode=1 +
 *     authenticated BE user).
 *   - `@ochorocho/revealjs-editor/Vendor/shiki/shiki-bundle.mjs` — the
 *     vendored, esbuild-bundled, self-contained Shiki ESM (~160 KB
 *     gzipped, our 10 languages + one-dark-pro + JavaScript regex engine,
 *     no WASM). Generated by `npm run build:shiki`; committed to the repo.
 *     ShikiHighlight.js + RevealEditableShiki.js both `import` from this
 *     path; the prefix above resolves it to the public asset URL.
 *
 * `dependencies: ['core']` because the editable-shiki bridge imports
 * `@typo3/visual-editor/Frontend/stores/data-handler-store.js` which in
 * turn depends on the `core` package's importmap entries.
 */
